package remote

import (
	"context"
	"fmt"
	"net"
	"os/exec"
	"strconv"
	"strings"
)

// ValidateForwardTarget accepts IP literals and DNS hostnames, never SSH syntax.
func ValidateForwardTarget(host string, remotePort, localPort int) error {
	if remotePort < 1 || remotePort > 65535 || localPort < 1 || localPort > 65535 {
		return fmt.Errorf("ports must be between 1 and 65535")
	}
	if net.ParseIP(host) != nil {
		return nil
	}
	if len(host) == 0 || len(host) > 253 {
		return fmt.Errorf("invalid remote hostname")
	}
	for _, label := range strings.Split(strings.TrimSuffix(host, "."), ".") {
		if len(label) == 0 || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return fmt.Errorf("invalid remote hostname")
		}
		for _, c := range label {
			if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-') {
				return fmt.Errorf("invalid remote hostname")
			}
		}
	}
	return nil
}

// BuildForwardCmd creates a dedicated, foreground SSH process. Disabling mux
// ensures killing this process also removes its listener, without affecting the
// host's RPC connection or terminal tabs. No local or remote shell is involved.
func BuildForwardCmd(ctx context.Context, alias, host string, remotePort, localPort int, opts SSHOptions) (*exec.Cmd, error) {
	if _, wsl := ParseWSLTarget(alias); wsl {
		return nil, fmt.Errorf("port forwarding is available for SSH hosts only")
	}
	if err := ValidateForwardTarget(host, remotePort, localPort); err != nil {
		return nil, err
	}
	opts.ControlMaster = "no"
	opts.NoTTY = true
	opts.ForceTTY = false
	opts.Interactive = false
	opts.ExtraOptions = append(append([]string{}, opts.ExtraOptions...), "GatewayPorts=no", "ControlMaster=no", "ControlPath=none", "ControlPersist=no", "ForkAfterAuthentication=no", "PermitLocalCommand=no", "RemoteCommand=none", "RequestTTY=no")
	cmd, err := BuildSSHCmd(ctx, alias, nil, opts)
	if err != nil {
		return nil, err
	}
	target := host
	if strings.Contains(target, ":") {
		target = "[" + target + "]"
	}
	spec := "127.0.0.1:" + strconv.Itoa(localPort) + ":" + target + ":" + strconv.Itoa(remotePort)
	// Place flags before the destination delimiter generated by BuildSSHCmd.
	for i, arg := range cmd.Args {
		if arg == "--" {
			args := append([]string{}, cmd.Args[:i]...)
			args = append(args, "-N", "-v", "-L", spec)
			cmd.Args = append(args, cmd.Args[i:]...)
			break
		}
	}
	return cmd, nil
}
